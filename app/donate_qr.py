def _key() -> bytes:
    return hashlib.sha256(("nfx|" + _S1 + "|" + _S2 + "|qr").encode()).digest()


def _stream(n: int) -> bytes:
    out = bytearray()
    i = 0
    k = _key()
    while len(out) < n:
        out += hashlib.sha256(k + i.to_bytes(4, "big")).digest()
        i += 1
    return bytes(out[:n])


def image_bytes() -> bytes:
    data = base64.b64decode(B64)
    plain = bytes(a ^ b for a, b in zip(data, _stream(len(data))))
    return zlib.decompress(plain)


def verify() -> bool:
    try:
        return hashlib.sha256(image_bytes()).hexdigest() == SHA256
    except Exception:
        return False
